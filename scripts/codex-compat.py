class CompatibilityError(ValueError):
    """An input or output needs review rather than an automatic rewrite."""


def normalized(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def read(path: Path) -> str:
    return normalized(path.read_text(encoding="utf-8"))


def fingerprint(path: Path) -> str:
    return hashlib.sha256(read(path).encode("utf-8")).hexdigest()


def safe_path(root: Path, relative: str) -> Path:
    """Reject traversal and symlink/junction parents before any read or write."""
    path = root / relative
    try:
        path.resolve().relative_to(root.resolve())
    except ValueError as exc:
        raise CompatibilityError(f"Path escapes repository: {relative}") from exc
    current = root
    for part in Path(relative).parts:
        if part in ("..", ".") or Path(relative).is_absolute():
            raise CompatibilityError(f"Unsafe relative path: {relative}")
        current = current / part
        if current.is_symlink() or getattr(os.path, "isjunction", lambda p: False)(current):
            raise CompatibilityError(f"Symlink/junction requires review: {relative}")
    return path


def scalar(value: str) -> str:
    """Only the scalar syntax actually used by the reviewed frontmatter."""
    if value.startswith('"'):
        try:
            result = json.loads(value)
        except json.JSONDecodeError as exc:
            raise CompatibilityError(f"Unsupported quoted scalar: {value}") from exc
        if not isinstance(result, str):
            raise CompatibilityError("Expected a string")
        return result
    if value.startswith("'"):
        if not value.endswith("'") or len(value) < 2:
            raise CompatibilityError("Unterminated scalar")
        return value[1:-1].replace("''", "'")
    if not value or value[0] in "&*!>{[" or "\t" in value:
        raise CompatibilityError(f"Unsupported scalar: {value!r}")
    return value


def frontmatter(text: str, kind: str) -> dict:
    """Conservative reader of the observed subset; this is not a general YAML parser.

    Supports plain/quoted descriptions, literal/folded description blocks, JSON
    inline lists, quoted block lists, booleans, and opaque nested metadata.
    Unknown top-level keys and unrecognized syntax fail instead of disappearing.
    """
    lines = normalized(text).splitlines()
    if not lines or lines[0] != "---":
        if kind == "rules":
            return {}
        raise CompatibilityError("Missing frontmatter")
    try:
        end = lines.index("---", 1)
    except ValueError as exc:
        raise CompatibilityError("Unterminated frontmatter") from exc
    result = {}
    index = 1
    while index < end:
        line = lines[index]
        index += 1
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        match = re.fullmatch(r"([A-Za-z][\w-]*):[ \t]*(.*)", line)
        if not match:
            raise CompatibilityError(f"Unsupported frontmatter line: {line!r}")
        key, value = match.groups()
        if key not in FIELDS[kind] or key in result:
            raise CompatibilityError(f"Unknown or duplicate {kind} key: {key}")
        block = []
        while index < end and (not lines[index].strip() or lines[index][0].isspace()
                               or lines[index].lstrip().startswith("#")):
            block.append(lines[index])
            index += 1
        if key == "metadata":
            if value or not any(item.strip() for item in block):
                raise CompatibilityError("Unsupported metadata layout")
            result[key] = "\n".join(block)
        elif key == "description" and value in ("|", ">"):
            result[key] = " ".join(item.strip() for item in block if item.strip())
        elif key in ("paths", "allowed-tools", "disallowed-tools"):
            if value:
                try:
                    items = json.loads(value)
                except json.JSONDecodeError as exc:
                    raise CompatibilityError(f"Unsupported list for {key}") from exc
            else:
                items = []
                for item in block:
                    if not item.strip() or item.lstrip().startswith("#"):
                        continue
                    entry = re.fullmatch(r"\s+-\s+(.+)", item)
                    if not entry:
                        raise CompatibilityError(f"Unsupported list item: {item}")
                    items.append(scalar(entry[1]))
            if not isinstance(items, list) or not all(isinstance(x, str) and x for x in items):
                raise CompatibilityError(f"Expected string list for {key}")
            result[key] = items
        elif key in ("disable-model-invocation", "alwaysApply"):
            if value not in ("true", "false"):
                raise CompatibilityError(f"Expected boolean for {key}")
            result[key] = value == "true"
        else:
            if any(item.strip() and not item.lstrip().startswith("#") for item in block):
                raise CompatibilityError(f"Unexpected continuation for {key}")
            result[key] = scalar(value)
    if kind in ("skills", "agents"):
        if not result.get("name") or not result.get("description"):
            raise CompatibilityError("Name and description are required")
        requested = result.get("allowed-tools", []) + result.get("disallowed-tools", [])
        if "tools" in result:
            requested += [x.strip() for x in result["tools"].split(",")]
        if set(requested) - TOOLS:
            raise CompatibilityError(f"Unreviewed tools: {sorted(set(requested) - TOOLS)}")
    return result


def source_files(root: Path, kind: str) -> dict[str, Path]:
    directory = safe_path(root, f".claude/{kind}")
    paths = directory.glob("*/SKILL.md") if kind == "skills" else directory.glob("*")
    found = {p.parent.name if kind == "skills" else p.name if kind == "hooks" else p.stem: p
             for p in paths if p.is_file() and (kind == "hooks" or p.suffix == ".md")}
    if set(found) != REVIEWED[kind]:
        raise CompatibilityError(
            f"Review {kind} inventory: new={sorted(set(found) - REVIEWED[kind])}; "
            f"missing={sorted(REVIEWED[kind] - set(found))}")
    return found


def adapter(name: str, metadata: dict, digest: str) -> str:
    sentence = re.split(r"(?<=[.!?])\s+", metadata["description"], maxsplit=1)[0]
    if len(sentence) > 240:
        sentence = sentence[:237].rsplit(" ", 1)[0] + "..."
    description = f"This repository's {name} workflow. {sentence}"
    arguments = metadata.get("argument-hint", "Use the inputs described in the original skill.")
    independence = ("\nThis workflow contains independence-sensitive review. Apply the bridge's\n"
                    "context and filesystem checks before that step; otherwise report it unverified.\n"
                    if name in INDEPENDENT else "")
    invocation = ("\nThis workflow is explicit-only. Start it only on explicit user intent or as\n"
                  "a permitted step of an already authorized workflow; do not start it\n"
                  "merely because its description matches the task.\n"
                  if metadata.get("disable-model-invocation", False) else "")
    return (f"---\nname: academic-{name}\ndescription: {json.dumps(description, ensure_ascii=False)}\n"
            f"---\n\n{MARKER}\n<!-- Canonical source SHA-256 (LF): {digest} -->\n\n"
            f"# Academic workflow: {name}\n\n"
            "Read [the platform bridge](../../../.codex/bridge.md) first. Then read\n"
            f"[the original skill](../../../.claude/skills/{name}/SKILL.md) in full\n"
            "and follow its procedure through the bridge. Load applicable rules from\n"
            "[the source map](../../../.codex/upstream-map.json).\n\n"
            f"Original argument convention: {arguments}\n\n"
            "Resolve supporting links from the original skill's directory. Its Claude\n"
            "frontmatter does not grant tools, isolate reviewers, or select Codex models.\n"
            "Check required capabilities and preserve the original verification gates.\n"
            + invocation + independence)


def expected_outputs(root: Path) -> dict[str, str]:
    manifest = {"schema_version": 1,
                "generator": "scripts/codex-compat.py",
                "runtime_status": "Not certified by generation or structural validation.",
                "skills": {}, "agents": {}, "rules": {}, "hooks": {}, "shared": {}}
    outputs = {}
    for kind in REVIEWED:
        for name, path in sorted(source_files(root, kind).items()):
            relative = path.relative_to(root).as_posix()
            safe_path(root, relative)
            entry = {"source": relative, "sha256_lf": fingerprint(path)}
            if kind == "hooks":
                entry["status"] = "not-wired-in-codex"
            else:
                try:
                    metadata = frontmatter(read(path), kind)
                except CompatibilityError as exc:
                    raise CompatibilityError(f"{relative}: {exc}") from exc
                if kind != "rules" and metadata["name"] != name:
                    raise CompatibilityError(f"{relative}: directory/name mismatch")
                if kind == "skills":
                    entry["explicit_only"] = metadata.get("disable-model-invocation", False)
                    entry["status"] = "excluded" if name in EXCLUDED else "reference-adapter"
                    entry["independence_check_required"] = name in INDEPENDENT
                    entry["adapter"] = None if name in EXCLUDED else f"{PREFIX}{name}/SKILL.md"
                    if name in EXCLUDED:
                        entry["reason"] = EXCLUDED[name]
                    else:
                        outputs[entry["adapter"]] = adapter(name, metadata, entry["sha256_lf"])
                        if entry["explicit_only"]:
                            outputs[f"{PREFIX}{name}/agents/openai.yaml"] = (
                                "# Generated by scripts/codex-compat.py; do not edit.\n"
                                "policy:\n  allow_implicit_invocation: false\n")
                elif kind == "agents":
                    entry.update(status="role-instructions-only",
                                 claude_model=metadata.get("model"),
                                 claude_effort=metadata.get("effort"))
                else:
                    entry.update(status="explicit-instruction-loading",
                                 scopes=metadata.get("paths", []))
                    if "alwaysApply" in metadata:
                        entry["claude_alwaysApply"] = metadata["alwaysApply"]
            manifest[kind][name] = entry
    # Track the shared material too, without copying it or pinning mutable Git refs.
    shared = {p for pattern in (".claude/references/**/*", ".claude/output-styles/*",
                               ".claude/scripts/*", "scripts/**/*", ".githooks/*")
              for p in root.glob(pattern) if p.is_file()
              and "__pycache__" not in p.parts and p.suffix not in (".pyc", ".pyo")}
    shared.update(root / rel for rel in ("CLAUDE.md", "MEMORY.md", ".claude/settings.json",
                  ".claude/WORKFLOW_QUICK_REF.md", ".github/workflows/gates.yml",
                  ".github/workflows/deploy.yml"))
    shared.difference_update({root / "scripts/codex-compat.py", root / "scripts/test-codex-compat.py"})
    # WindowsPath compares without case; PosixPath does not. Serialize by the
    # literal relative string so scripts/R has the same order on both systems.
    for path in sorted(shared, key=lambda item: item.relative_to(root).as_posix()):
        relative = path.relative_to(root).as_posix()
        manifest["shared"][relative] = fingerprint(safe_path(root, relative))
    outputs[MAP_PATH] = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
    return outputs


def validate_links(root: Path, outputs: dict[str, str]) -> None:
    documents = {k: v for k, v in outputs.items() if k.endswith(".md")}
    for relative in ("AGENTS.md", ".codex/bridge.md", ".codex/README.md"):
        path = safe_path(root, relative)
        documents[relative] = read(path)
    for relative, content in documents.items():
        for target in re.findall(r"\[[^\]]*\]\(([^)]+)\)", content):
            if target.startswith(("https://", "http://", "#")):
                continue
            target = target.partition("#")[0]
            path = (root / relative).parent / target
            try:
                resolved = path.resolve().relative_to(root.resolve()).as_posix()
            except ValueError as exc:
                raise CompatibilityError(f"{relative}: link leaves repository: {target}") from exc
            if resolved not in outputs and not safe_path(root, resolved).is_file():
                raise CompatibilityError(f"{relative}: broken reference: {target}")


def synchronize(root: Path, generate: bool = False) -> list[str]:
    root = root.resolve()
    outputs = expected_outputs(root)
    validate_links(root, outputs)
    discovered = {p.relative_to(root).as_posix()
                  for p in (root / ".agents/skills").glob("academic-*/**/*") if p.is_file()}
    unexpected = sorted(discovered - outputs.keys())
    if unexpected:
        raise CompatibilityError(f"Review unexpected adapter files; nothing deleted: {unexpected}")
    changed = []
    for relative, expected in outputs.items():
        path = safe_path(root, relative)
        if path.exists() and not path.is_file():
            raise CompatibilityError(f"Output is not a file: {relative}")
        if path.exists() and read(path) == expected:
            continue
        if generate and path.exists():
            if relative == MAP_PATH:
                try:
                    owned = json.loads(read(path)).get("generator") == "scripts/codex-compat.py"
                except (ValueError, AttributeError):
                    owned = False
            else:
                owned = "Generated by scripts/codex-compat.py; do not edit." in read(path)
            if not owned:
                raise CompatibilityError(f"Refusing to overwrite an unowned file: {relative}")
        changed.append(relative)
    # Preflight every output before writing anything. Never remove stale files.
    if generate:
        for relative in changed:
            path = safe_path(root, relative)
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("w", encoding="utf-8", newline="\n") as stream:
                stream.write(outputs[relative])
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="report drift without writing")
    mode.add_argument("--generate", action="store_true", help="update owned generated files after review")
    args = parser.parse_args(argv)
    try:
        changed = synchronize(ROOT, generate=args.generate)
    except (CompatibilityError, OSError, UnicodeError) as exc:
        print(f"codex-compat: {exc}", file=sys.stderr)
        return 2
    if changed and args.check:
        print("codex-compat: drift; review upstream, then run --generate:")
        print("\n".join(f"  {name}" for name in changed))
        return 1
    outputs = expected_outputs(ROOT)
    count = sum(path.endswith('/SKILL.md') for path in outputs)
    policies = sum(path.endswith('/openai.yaml') for path in outputs)
    print(f"codex-compat: {'generated ' + str(len(changed)) + ' files' if args.generate else 'current'}; "
          f"{count} reference adapters, {policies} explicit-only policies; runtime behavior not certified")
    return 0


if __name__ == "__main__":
    sys.exit(main())
